export const MockDocumentProvider = {
  getDocuments: async (): Promise<BrandDocument[]> => {
    return new Promise((resolve) => {
      setTimeout(() => resolve([...mockDocuments]), 300);
    });
  },

  uploadDocument: async (file: File, category: string): Promise<BrandDocument> => {
    return new Promise((resolve, reject) => {
      setTimeout(() => {
        if (file.size > 10 * 1024 * 1024) {
          reject(new Error('File too large'));
          return;
        }

        const newDoc: BrandDocument = {
          id: uuidv4(),
          name: file.name,
          type: file.type || 'application/octet-stream',
          source: 'upload',
          status: 'active',
          file_size: file.size,
          category,
          processing_status: 'READY',
          retrieval_status: 'READY',
          uploaded_by: 'mock-user',
          created_at: new Date().toISOString(),
          updated_at: new Date().toISOString(),
          extracted_text: `# ${file.name}\n\nDocument uploaded and parsed for Brand Brain vector indexing.`,
          metadata_json: {
            word_count: Math.floor(Math.random() * 2000) + 500
          }
        };

        mockDocuments = [newDoc, ...mockDocuments];
        resolve(newDoc);
      }, 500);
    });
  },

  createDocument: async (data: { name: string; content: string; category?: string; type?: string }): Promise<BrandDocument> => {
    return new Promise((resolve) => {
      const newDoc: BrandDocument = {
        id: uuidv4(),
        name: data.name,
        type: data.type || 'text/markdown',
        source: 'manual',
        status: 'active',
        file_size: data.content.length,
        category: data.category || 'Product Information',
        processing_status: 'READY',
        retrieval_status: 'READY',
        uploaded_by: 'mock-user',
        created_at: new Date().toISOString(),
        updated_at: new Date().toISOString(),
        extracted_text: data.content,
        metadata_json: { word_count: data.content.split(/\s+/).length }
      };
      mockDocuments = [newDoc, ...mockDocuments];
      resolve(newDoc);
    });
  },

  generateRealDocuments: async (): Promise<BrandDocument[]> => {
    return new Promise((resolve) => {
      resolve([...mockDocuments]);
    });
  },

  deleteDocument: async (id: string): Promise<void> => {
    return new Promise((resolve, reject) => {
      setTimeout(() => {
        const initialLen = mockDocuments.length;
        mockDocuments = mockDocuments.filter(d => d.id !== id);
        if (mockDocuments.length === initialLen) {
          reject(new Error('Document not found'));
        } else {
          resolve();
        }
      }, 300);
    });
  }
};
